"""Generate supabase/seed.sql from supabase/questions/<slug>/.

Usage: python supabase/scripts/build_seed.py [--check]
  --check  exit 1 if supabase/seed.sql differs from the generated output.
"""
import json
import sys
import uuid
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
SUPABASE = SCRIPTS.parent
QUESTIONS = SUPABASE / "questions"
SEED = SUPABASE / "seed.sql"
NAMESPACE = uuid.UUID("6f1c1e2a-5b7d-4c53-9a11-0d5e7b1f3a42")


def read(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def uid(*parts):
    return str(uuid.uuid5(NAMESPACE, "/".join(parts)))


class Quoter:
    """Dollar-quotes strings with a tag that never appears in any content."""

    def __init__(self, corpus):
        n = 0
        while ("$q%d$" % n) in corpus or ("q%d$" % n) in corpus:
            n += 1
        self.tag = "$q%d$" % n

    def __call__(self, text):
        assert self.tag not in text
        return "%s%s%s" % (self.tag, text, self.tag)


def load_question(qdir):
    slug = qdir.name
    meta = json.loads(read(qdir / "question.json"))
    files = {}
    for kind, folder in (("buggy", "buggy"), ("test", "tests")):
        for p in sorted((qdir / folder).glob("*.py")):
            files[(kind, p.name)] = read(p)
    ref = {p.name: read(p) for p in sorted((qdir / "reference").glob("*.py"))}
    # Optional hidden acceptance tests: shown to the interviewer only, stored
    # with the reference files under an "acceptance/" path.
    for p in sorted((qdir / "acceptance").glob("*.py")):
        ref["acceptance/" + p.name] = read(p)
    return slug, meta, files, ref


def build():
    loaded = [load_question(d) for d in sorted(QUESTIONS.iterdir()) if d.is_dir()]
    corpus = "".join(
        json.dumps(m) + "".join(f.values()) + "".join(r.values())
        for _, m, f, r in loaded
    )
    q = Quoter(corpus)
    out = [
        "-- GENERATED by supabase/scripts/build_seed.py. Do not edit by hand.",
        "-- Idempotent: safe to run repeatedly.",
        "begin;",
        "",
    ]
    for slug, meta, files, ref in loaded:
        qid = uid("question", slug)
        out.append("-- question: %s" % slug)
        out.append(
            "insert into public.questions (id, slug, title, prompt, constraints, language) values "
            "('%s', %s, %s, %s, %s, %s)\n"
            "on conflict (id) do update set slug = excluded.slug, title = excluded.title, "
            "prompt = excluded.prompt, constraints = excluded.constraints, language = excluded.language;"
            % (qid, q(slug), q(meta["title"]), q(meta["prompt"]),
               q(meta.get("constraints", "")), q(meta.get("language", "python")))
        )
        out.append(
            "insert into public.question_private (question_id, checklist, followups, rubric) values "
            "('%s', %s::jsonb, %s::jsonb, %s::jsonb)\n"
            "on conflict (question_id) do update set checklist = excluded.checklist, "
            "followups = excluded.followups, rubric = excluded.rubric;"
            % (qid, q(json.dumps(meta["checklist"], indent=1)),
               q(json.dumps(meta["followups"], indent=1)),
               q(json.dumps(meta["rubric"], indent=1)))
        )

        def upsert_children(table, cols, rows):
            ids = [r[0] for r in rows]
            vals = ",\n".join("  (%s)" % ", ".join(r_) for r_ in rows_sql(rows))
            sets = ", ".join("%s = excluded.%s" % (c, c) for c in cols[1:])
            out.append("insert into public.%s (%s) values\n%s\non conflict (id) do update set %s;"
                       % (table, ", ".join(cols), vals, sets))
            out.append("delete from public.%s where question_id = '%s' and id not in (%s);"
                       % (table, qid, ", ".join("'%s'" % i for i in ids)))

        def rows_sql(rows):
            for r in rows:
                yield ["'%s'" % r[0], "'%s'" % qid] + [
                    q(v) if isinstance(v, str) else str(v) for v in r[1:]
                ]

        upsert_children(
            "question_files", ["id", "question_id", "path", "content", "kind"],
            [(uid("file", slug, kind, path), path, content, kind)
             for (kind, path), content in sorted(files.items())],
        )
        upsert_children(
            "question_reference_files", ["id", "question_id", "path", "content"],
            [(uid("ref", slug, path), path, content) for path, content in sorted(ref.items())],
        )
        upsert_children(
            "question_bugs", ["id", "question_id", "title", "description", "file_path", "hint"],
            [(uid("bug", slug, str(i)), b["title"], b["description"], b["file_path"], b.get("hint", ""))
             for i, b in enumerate(meta["bugs"])],
        )
        out.append("")
    out.append("commit;")
    return "\n".join(out) + "\n"


def main(argv):
    sql = build()
    if "--check" in argv:
        current = SEED.read_text(encoding="utf-8") if SEED.exists() else ""
        if current.replace("\r\n", "\n") != sql:
            print("seed.sql is out of date; run: python supabase/scripts/build_seed.py")
            return 1
        print("seed.sql is up to date")
        return 0
    with open(SEED, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(sql)
    print("wrote %s (%d bytes)" % (SEED, len(sql)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
